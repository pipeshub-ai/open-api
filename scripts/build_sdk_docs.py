#!/usr/bin/env python3
"""Build the versioned SDK pages of the Mintlify docs site from released SDK tags.

For every release tag the three SDK repos share (vX.Y.Z), it writes into the docs checkout:
  sdks/<tag>/openapi.yaml   the spec that release was generated from, with Python, TypeScript
                            and Go x-codeSamples on every operation (Mintlify shows them as tabs)
  sdks/<tag>/{python,typescript,go}.mdx   each SDK's README at that tag, converted to MDX
and rebuilds the "SDKs" tab of docs.json: one version per sdks/v*/ directory, newest first.

Where a release's spec comes from: the SDK repos are generated by this repo's generate-sdks.yml,
whose commits say "Spec commit: <open-api sha>". The newest such line before the tag names the
open-api commit, and source_specs/pipeshub-sdk-openapi.yaml at that commit is the spec.

Usage:
  build_sdk_docs.py --sdks DIR --open-api DIR --docs DIR [--versions v2.0.1,v2.0.0] [--min-version v1.6.0]
DIR for --sdks holds pipeshub-sdk-{python,typescript,go} clones with tags. Needs the speakeasy CLI
(and SPEAKEASY_API_KEY in CI) and PyYAML.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

import yaml

# lang -> (SDK repo, display name)
LANGS = {
    "python": ("pipeshub-sdk-python", "Python"),
    "typescript": ("pipeshub-sdk-typescript", "TypeScript"),
    "go": ("pipeshub-sdk-go", "Go"),
}
TAG_RE = re.compile(r"^v\d+\.\d+\.\d+$")
SPEC_COMMIT_RE = re.compile(r"Spec commit: ([0-9a-f]{7,40})")
TARGET_RE = re.compile(r'^\$\["paths"\]\["([^"]+)"\]\["([a-z]+)"\]$')
SPEC_PATH = "source_specs/pipeshub-sdk-openapi.yaml"
SDK_TAB = "SDKs"
# README sections that do not belong on a docs page; the API reference tab replaces the last one.
DROP_SECTIONS = {"Table of Contents", "Summary", "IDE Support"}
OPERATIONS_SECTION = "Available Resources and Operations"


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True).stdout


def semver(tag: str) -> tuple[int, ...]:
    return tuple(int(p) for p in tag.lstrip("v").split("."))


def shared_tags(sdks: Path, min_version: str) -> list[str]:
    tag_sets = [{t for t in git(sdks / repo, "tag").split() if TAG_RE.match(t)} for repo, *_ in LANGS.values()]
    tags = set.intersection(*tag_sets)
    return sorted((t for t in tags if semver(t) >= semver(min_version)), key=semver, reverse=True)


def spec_commit(sdks: Path, tag: str) -> str:
    shas = set()
    for repo, *_ in LANGS.values():
        m = SPEC_COMMIT_RE.search(git(sdks / repo, "log", tag, "--format=%B"))
        if not m:
            raise SystemExit(f"{repo}@{tag}: no 'Spec commit:' line in its history")
        shas.add(m.group(1))
    if len(shas) != 1:
        raise SystemExit(f"{tag}: the SDKs were generated from different spec commits {sorted(shas)}")
    return shas.pop()


def code_samples(sdk_repo: Path, tag: str, lang: str, spec_file: Path, work: Path) -> dict:
    """Run speakeasy with the SDK's own gen.yaml at that tag, so snippets match that release."""
    cfg = work / f"{lang}-config"
    cfg.mkdir()
    (cfg / "gen.yaml").write_text(git(sdk_repo, "show", f"{tag}:.speakeasy/gen.yaml"))
    out = work / f"{lang}-samples.yaml"
    subprocess.run(
        ["speakeasy", "generate", "codeSamples", "-s", str(spec_file), "-l", lang,
         "--config-path", str(cfg), "--out", str(out)],
        check=True, capture_output=True, text=True,
    )
    return yaml.safe_load(out.read_text())


def add_samples(spec: dict, overlay: dict, label: str) -> int:
    count = 0
    for action in overlay["actions"]:
        m = TARGET_RE.match(action["target"])
        if not m:
            raise SystemExit(f"unexpected code-sample target {action['target']!r}")
        operation = spec["paths"][m.group(1)][m.group(2)]
        for sample in action["update"]["x-codeSamples"]:
            operation.setdefault("x-codeSamples", []).append(
                {"lang": sample["lang"], "label": label, "source": sample["source"]})
            count += 1
    return count


def repair_spec(spec: dict, tag: str) -> None:
    """Old release specs have two OpenAPI 3.0 errors that Mintlify rejects; later specs fixed both.
    `content: {schema: ...}` without a media type becomes application/json (what the API returns),
    and a `{type: "null"}` member of anyOf/oneOf becomes `nullable: true`."""
    def walk(node, where):
        if isinstance(node, dict):
            content = node.get("content")
            if isinstance(content, dict) and "schema" in content:
                node["content"] = {"application/json": content}
                print(f"  {tag}: repaired content without a media type at {where}")
            for key in ("anyOf", "oneOf"):
                members = node.get(key)
                if isinstance(members, list) and {"type": "null"} in members:
                    node[key] = [m for m in members if m != {"type": "null"}]
                    node["nullable"] = True
                    print(f"  {tag}: repaired type null at {where}")
            for k, v in node.items():
                walk(v, f"{where}/{k}")
        elif isinstance(node, list):
            for i, v in enumerate(node):
                walk(v, f"{where}/{i}")
    walk(spec.get("paths", {}), "paths")
    walk(spec.get("components", {}), "components")


class _BlockDumper(yaml.SafeDumper):
    pass


_BlockDumper.add_representer(
    str, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|" if "\n" in s else None))


# --- README -> MDX -------------------------------------------------------------------------

def _split_fenced(text: str) -> list[tuple[bool, str]]:
    """[(is_code, chunk)], where code chunks are whole ``` fenced blocks."""
    parts, buf, in_code = [], [], False
    for line in text.splitlines(keepends=True):
        if line.lstrip().startswith("```"):
            if in_code:
                buf.append(line)
                parts.append((True, "".join(buf)))
                buf, in_code = [], False
                continue
            if buf:
                parts.append((False, "".join(buf)))
            buf, in_code = [line], True
            continue
        buf.append(line)
    if buf:
        parts.append((in_code, "".join(buf)))
    return parts


ALLOWED_TAGS = re.compile(r"<(?!/?(?:Accordion|Note|Tip|Info|Warning|br)\b)")
ALERT_RE = re.compile(r"^> \[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)\]\n((?:>.*\n?)*)", re.M)
ALERT_TAGS = {"NOTE": "Note", "TIP": "Tip", "IMPORTANT": "Info", "WARNING": "Warning", "CAUTION": "Warning"}


def _alert(m: re.Match) -> str:
    """GitHub alert blockquote -> Mintlify callout."""
    tag = ALERT_TAGS[m.group(1)]
    body = re.sub(r"^> ?", "", m.group(2), flags=re.M).strip()
    return f"<{tag}>\n{body}\n</{tag}>\n"


def _escape_prose(text: str, blob: str) -> str:
    text = re.sub(r"<!--.*?-->\n?", "", text, flags=re.S)
    text = re.sub(r"</br>|<br>", "<br />", text)
    text = re.sub(r"<details(?: open)?>\s*<summary>(.*?)</summary>", r'<Accordion title="\1">', text, flags=re.S)
    text = text.replace("</details>", "</Accordion>")
    text = ALERT_RE.sub(_alert, text)
    # Relative links point into the SDK repo at this tag.
    text = re.sub(r"\]\((?!https?://|#|mailto:)\.?/?([^)]+)\)", rf"]({blob}/\1)", text)
    out = []
    for i, piece in enumerate(re.split(r"(`[^`\n]*`)", text)):
        if i % 2:  # inline code is literal in MDX
            out.append(piece)
        else:
            out.append(ALLOWED_TAGS.sub("&lt;", piece).replace("{", "\\{").replace("}", "\\}"))
    return "".join(out)


def readme_to_mdx(readme: str, lang: str, tag: str) -> str:
    repo, name = LANGS[lang]
    blob = f"https://github.com/pipeshub-ai/{repo}/blob/{tag}"
    body = re.sub(r"\A#\s[^\n]*\n", "", readme)  # the H1 becomes the page title

    # Split into ## sections, fence-aware so "## " inside code is not a heading.
    sections, current = [], ["", []]
    for is_code, chunk in _split_fenced(body):
        if is_code:
            current[1].append((True, chunk))
            continue
        for line in chunk.splitlines(keepends=True):
            if line.startswith("## "):
                sections.append(current)
                current = [line[3:].strip(), []]
            elif current[1] and not current[1][-1][0]:
                current[1][-1] = (False, current[1][-1][1] + line)
            else:
                current[1].append((False, line))
    sections.append(current)

    parts = []
    for heading, chunks in sections:
        if heading in DROP_SECTIONS:
            continue
        if heading == OPERATIONS_SECTION:
            parts.append(f"## {heading}\n\nEvery method, with its parameters and responses, is in the "
                         f"API reference of this version and in the [SDK repository]({blob}/README.md#"
                         "available-resources-and-operations).\n\n")
            continue
        if heading:
            parts.append(f"## {heading}\n")
        parts += [c if code else _escape_prose(c, blob) for code, c in chunks]
    content = re.sub(r"\n{3,}", "\n\n", "".join(parts)).strip()

    return (
        f'---\ntitle: "{name} SDK"\n'
        f'description: "Install and use the PipesHub {name} SDK, release {tag}."\n---\n\n'
        f"<Note>\nThis page is the [{name} SDK README at {tag}]({blob}/README.md). "
        "Use the version menu to see another release.\n</Note>\n\n"
        f"{content}\n"
    )


# --- docs.json ------------------------------------------------------------------------------

def update_nav(docs: Path) -> list[str]:
    versions = sorted((p.name for p in (docs / "sdks").iterdir() if p.is_dir() and TAG_RE.match(p.name)),
                      key=semver, reverse=True)
    path = docs / "docs.json"
    config = json.loads(path.read_text())
    tab = next((t for t in config["navigation"].get("tabs", []) if t.get("tab") == SDK_TAB), None)
    if tab is None:
        raise SystemExit(f'docs.json has no "{SDK_TAB}" tab under navigation.tabs; add it once by hand')
    tab["versions"] = [
        {
            "version": v,
            **({"tag": "Latest"} if i == 0 else {}),
            "groups": [
                {"group": "Get started", "pages": ["sdks/overview", *[f"sdks/{v}/{lang}" for lang in LANGS]]},
                {"group": "API reference", "openapi": {"source": f"sdks/{v}/openapi.yaml", "directory": f"sdks/{v}/api"}},
            ],
        }
        for i, v in enumerate(versions)
    ]
    path.write_text(json.dumps(config, indent=2, ensure_ascii=False) + "\n")
    return versions


def build_version(tag: str, sdks: Path, open_api: Path, docs: Path) -> None:
    sha = spec_commit(sdks, tag)
    out_dir = docs / "sdks" / tag
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        spec_file = work / "spec.yaml"
        spec_file.write_text(git(open_api, "show", f"{sha}:{SPEC_PATH}"))
        spec = yaml.safe_load(spec_file.read_text())
        repair_spec(spec, tag)
        counts = {}
        for lang, (repo, name) in LANGS.items():
            counts[name] = add_samples(spec, code_samples(sdks / repo, tag, lang, spec_file, work), name)
        if out_dir.exists():
            shutil.rmtree(out_dir)
        out_dir.mkdir(parents=True)
        (out_dir / "openapi.yaml").write_text(
            yaml.dump(spec, Dumper=_BlockDumper, sort_keys=False, allow_unicode=True, width=10_000))
    for lang, (repo, *_) in LANGS.items():
        (out_dir / f"{lang}.mdx").write_text(readme_to_mdx(git(sdks / repo, "show", f"{tag}:README.md"), lang, tag))
    print(f"{tag}: spec {sha}, code samples {counts}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sdks", type=Path, required=True)
    ap.add_argument("--open-api", type=Path, required=True)
    ap.add_argument("--docs", type=Path, required=True)
    ap.add_argument("--versions", default="", help="comma-separated tags; default: every shared tag >= --min-version")
    ap.add_argument("--min-version", default="v1.6.0")
    args = ap.parse_args()

    tags = [t.strip() for t in args.versions.split(",") if t.strip()] or shared_tags(args.sdks, args.min_version)
    if not tags:
        raise SystemExit("no SDK tags to build")
    for tag in tags:
        if not TAG_RE.match(tag):
            raise SystemExit(f"not a release tag: {tag!r}")
        build_version(tag, args.sdks, args.open_api, args.docs)
    print("docs.json SDK versions:", ", ".join(update_nav(args.docs)))


if __name__ == "__main__":
    main()
